function forDegree(signName, degree){
  const entries = SABIAN[signName];
  if(!entries || !entries.length) return null;
  // 找最接近的 entry
  let closest = entries[0];
  let minDiff = Math.abs(degree - entries[0].d);
  for(const e of entries){
    const diff = Math.abs(degree - e.d);
    if(diff < minDiff){ minDiff = diff; closest = e; }
  }
  return { symbol: closest.s, meaning: closest.m, atDegree: closest.d, sign: signName };
}

